USE `maha_sarakham_travel`;

-- --------------------------------------------------------
-- 1. Table structure for table `categories` (ประเภทสถานที่)
-- --------------------------------------------------------
DROP TABLE IF EXISTS `attractions`;
DROP TABLE IF EXISTS `categories`;
DROP TABLE IF EXISTS `admins`;

CREATE TABLE `categories` (
  `id` INT(11) NOT NULL AUTO_INCREMENT,
  `name` VARCHAR(100) NOT NULL,
  `slug` VARCHAR(100) NOT NULL,
  `description` TEXT DEFAULT NULL,
  `icon` VARCHAR(50) DEFAULT 'bi-geo-alt',
  `created_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `slug_unique` (`slug`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- --------------------------------------------------------
-- 2. Table structure for table `attractions` (แหล่งท่องเที่ยว 15 แห่ง)
-- --------------------------------------------------------
CREATE TABLE `attractions` (
  `id` INT(11) NOT NULL AUTO_INCREMENT,
  `category_id` INT(11) NOT NULL,
  `name_th` VARCHAR(150) NOT NULL,
  `name_en` VARCHAR(150) DEFAULT NULL,
  `slug` VARCHAR(150) NOT NULL,
  `history` TEXT DEFAULT NULL,
  `highlights` TEXT DEFAULT NULL,
  `opening_time` TIME DEFAULT NULL,
  `closing_time` TIME DEFAULT NULL,
  `is_open_24_hours` TINYINT(1) NOT NULL DEFAULT 0,
  `operating_days` VARCHAR(100) DEFAULT 'เปิดให้บริการทุกวัน',
  `admission_fee` VARCHAR(150) DEFAULT 'ยังไม่มีข้อมูลยืนยัน',
  `image_url` VARCHAR(255) DEFAULT 'assets/images/default.jpg',
  `address` TEXT DEFAULT NULL,
  `travel_info` TEXT DEFAULT 'ยังไม่มีข้อมูลยืนยัน',
  `google_maps_url` TEXT NOT NULL,
  `facilities` TEXT DEFAULT 'ยังไม่มีข้อมูลยืนยัน',
  `nearby_places` TEXT DEFAULT 'ยังไม่มีข้อมูลยืนยัน',
  `visitor_tips` TEXT DEFAULT 'ยังไม่มีข้อมูลยืนยัน',
  `status` ENUM('published', 'draft') NOT NULL DEFAULT 'published',
  `created_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `slug_unique` (`slug`),
  KEY `fk_attractions_category` (`category_id`),
  CONSTRAINT `fk_attractions_category` FOREIGN KEY (`category_id`) REFERENCES `categories` (`id`) ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- --------------------------------------------------------
-- 3. Table structure for table `admins` (ผู้ดูแลระบบ)
-- --------------------------------------------------------
CREATE TABLE `admins` (
  `id` INT(11) NOT NULL AUTO_INCREMENT,
  `username` VARCHAR(50) NOT NULL,
  `password_hash` VARCHAR(255) NOT NULL,
  `full_name` VARCHAR(100) NOT NULL,
  `created_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `username_unique` (`username`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

